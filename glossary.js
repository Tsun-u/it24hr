  const byId = new Map(TERMS.map(t => [t.id, t]));
  const LATIN = /[A-Za-z0-9_]/;
  const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  // 長的寫法排前面：同一個位置「母議題」先於「議題」、「開發計畫文件」先於「開發計畫」
  const PATTERNS = TERMS.flatMap(t => (t.match || [t.word]).map(text => ({ text, id: t.id }))).sort((a, b) => b.text.length - a.text.length);
  const ID_OF = new Map(PATTERNS.map(p => [p.text, p.id]));
  const pattern = () => new RegExp(PATTERNS.map(p => escape(p.text)).join('|'), 'g');
  // 英文詞前後不能接英數字：「SA」不吃「SAVE」、「502」不吃「1502」
  const bounded = (text, at, word) => !(LATIN.test(word[0]) && LATIN.test(text[at - 1] || ''))
    && !(LATIN.test(word[word.length - 1]) && LATIN.test(text[at + word.length] || ''));

  // 把一段字切成 [{ text }, { text, term }]；seen 是這一段裡已經標過的詞（同一段只標第一次），會被更新
  function segments(text, seen = new Set()) {
    const out = []; const re = pattern(); let last = 0; let m;
    while ((m = re.exec(text))) {
      const word = m[0], id = ID_OF.get(word);
      if (!bounded(text, m.index, word) || seen.has(id)) continue;
      seen.add(id);
      if (m.index > last) out.push({ text: text.slice(last, m.index) });
      out.push({ text: word, term: id });
      last = m.index + word.length;
    }
    if (last < text.length) out.push({ text: text.slice(last) });
    return out;
  }

